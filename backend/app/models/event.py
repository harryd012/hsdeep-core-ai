"""
Event model. An append-only log of discrete occurrences reported by a
MonitoringSource or generated by the platform itself (config changes,
reboots, logins, HA failovers, security events, etc). Unlike Sensor/Alert,
Events are never soft-deleted or mutated after creation - they are a
historical record. Deletion, if ever needed, is a hard retention purge, not
a user-facing soft delete, so this model intentionally has no
SoftDeleteMixin.
"""
from __future__ import annotations

import uuid
from datetime import datetime
from typing import TYPE_CHECKING

from sqlalchemy import DateTime, ForeignKey, Index, String, Text, text
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, TimestampMixin, UUIDPKMixin

if TYPE_CHECKING:
    from app.models.device import Device
    from app.models.monitoring_source import MonitoringSource
    from app.models.tenant import Tenant


class Event(Base, UUIDPKMixin, TimestampMixin):
    __tablename__ = "events"
    __table_args__ = (
        Index("ix_events_tenant_occurred", "tenant_id", "occurred_at"),
        Index(
            "uq_events_source_external_id",
            "monitoring_source_id",
            "external_id",
            unique=True,
            postgresql_where=text("external_id IS NOT NULL"),
        ),
    )

    tenant_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), ForeignKey("tenants.id", ondelete="CASCADE"), nullable=False, index=True
    )
    device_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("devices.id", ondelete="SET NULL"), nullable=True, index=True
    )
    monitoring_source_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("monitoring_sources.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )

    # The ID of this event inside the vendor's system, when applicable -
    # used together with monitoring_source_id to prevent duplicate ingestion
    # on repeated syncs. Null for platform-generated events.
    external_id: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # Normalized event category: config_change | reboot | login |
    # ha_failover | security | ... Free-form string (not an enum) so new
    # adapters/producers can introduce new event types without a migration.
    event_type: Mapped[str] = mapped_column(String(100), nullable=False, index=True)
    # critical | warning | info
    severity: Mapped[str] = mapped_column(
        String(20), nullable=False, default="info", server_default="info", index=True
    )
    message: Mapped[str] = mapped_column(Text, nullable=False)
    occurred_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False)

    # Full raw payload from the source, preserved verbatim for audit/replay.
    raw_payload: Mapped[dict] = mapped_column(JSONB, nullable=False, default=dict, server_default="{}")

    tenant: Mapped["Tenant"] = relationship()
    device: Mapped["Device | None"] = relationship()
    monitoring_source: Mapped["MonitoringSource | None"] = relationship()

    def __repr__(self) -> str:
        return f"<Event id={self.id} type={self.event_type!r} severity={self.severity!r}>"
